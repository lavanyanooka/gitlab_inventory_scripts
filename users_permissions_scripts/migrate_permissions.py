class GitHubClient:
    """HTTP client for the GitHub REST API with retry logic."""

    def __init__(self, token: str, dry_run: bool = False):
        self.token = token
        self.dry_run = dry_run
        self._session = requests.Session()
        self._session.headers.update({
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "X-GitHub-Api-Version": "2022-11-28",
        })

    def _request(self, method: str, endpoint: str, **kwargs: Any) -> requests.Response | None:
        """Make a request with retry logic."""
        url = f"{GITHUB_API_BASE}/{endpoint.lstrip('/')}"

        if self.dry_run and method != "GET":
            log.info("[DRY-RUN] %s %s %s", method, url, kwargs.get("json", ""))
            return None

        # Allow per-request header overrides
        extra_headers = kwargs.pop("headers", None)

        for attempt in range(1, MAX_RETRIES + 1):
            try:
                req_kwargs = dict(**kwargs)
                if extra_headers:
                    req_kwargs["headers"] = extra_headers
                resp = self._session.request(method, url, timeout=30, **req_kwargs)

                # Rate limit handling
                if resp.status_code == 403 and "rate limit" in resp.text.lower():
                    reset = resp.headers.get("X-RateLimit-Reset", "")
                    wait = max(float(reset) - time.time(), 1.0) if reset else 60.0
                    log.warning("Rate limited, sleeping %.0fs", wait)
                    time.sleep(wait)
                    continue

                if resp.status_code == 429:
                    retry_after = float(resp.headers.get("Retry-After", "60"))
                    log.warning("429 rate limited, sleeping %.0fs", retry_after)
                    time.sleep(retry_after)
                    continue

                if resp.status_code >= 500:
                    backoff = BACKOFF_BASE * (2 ** (attempt - 1))
                    log.warning("Server error %d, retrying in %.1fs", resp.status_code, backoff)
                    time.sleep(backoff)
                    continue

                return resp
            except (requests.exceptions.Timeout, requests.exceptions.ConnectionError) as e:
                backoff = BACKOFF_BASE * (2 ** (attempt - 1))
                log.warning("Request error: %s, retrying in %.1fs", e, backoff)
                time.sleep(backoff)

        log.error("Failed after %d retries: %s %s", MAX_RETRIES, method, url)
        return None

    def get(self, endpoint: str, **kwargs: Any) -> requests.Response | None:
        return self._request("GET", endpoint, **kwargs)

    def post(self, endpoint: str, **kwargs: Any) -> requests.Response | None:
        return self._request("POST", endpoint, **kwargs)

    def put(self, endpoint: str, **kwargs: Any) -> requests.Response | None:
        return self._request("PUT", endpoint, **kwargs)

    def patch(self, endpoint: str, **kwargs: Any) -> requests.Response | None:
        return self._request("PATCH", endpoint, **kwargs)



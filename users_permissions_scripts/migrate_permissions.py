#!/usr/bin/env python3
"""
GitLab-to-GitHub Permission Migration Execution Tool
=====================================================

Reads mapping CSV files (generated by users_permissions_inventory.py) and
the inventory Excel workbook, then creates GitHub teams, invites users,
and sets repository permissions via the GitHub REST API.

Prerequisites:
  1. Run users_permissions_inventory.py first to generate:
     - GitLab_UsersPermissions_Inventory.xlsx
     - gitlab_to_github_user_mapping.csv
     - gitlab_to_github_group_mapping.csv
     - gitlab_to_github_project_mapping.csv
  2. Fill in the GitHub columns in the mapping CSVs
  3. Create a GitHub PAT with: admin:org, repo, read:user scopes

Usage:
    python migrate_permissions.py --github-org my-org --github-token ghp_xxx --mappings-dir .
    python migrate_permissions.py --github-org my-org --github-token ghp_xxx --mappings-dir . --dry-run
    python migrate_permissions.py --github-org my-org --github-token ghp_xxx --mappings-dir . --skip-teams --skip-repos

Environment variables (CLI overrides take precedence):
    GITHUB_TOKEN - GitHub Personal Access Token
    GITHUB_ORG   - GitHub organization name
"""


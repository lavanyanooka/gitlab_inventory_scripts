def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="GitLab-to-GitHub Permission Migration Execution Tool",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s --github-org my-org --github-token ghp_xxx --mappings-dir .
  %(prog)s --github-org my-org --github-token ghp_xxx --mappings-dir . --dry-run
  %(prog)s --github-org my-org --github-token ghp_xxx --mappings-dir . --skip-teams

Workflow:
  1. Run users_permissions_inventory.py to generate inventory + mapping CSVs
  2. Fill in GitHub columns in the mapping CSVs
  3. Run this script with --dry-run first to validate
  4. Run without --dry-run to execute migration
""",
    )
    parser.add_argument("--github-org", required=True,
                        help="Target GitHub organization")
    parser.add_argument("--github-token",
                        default=os.environ.get("GITHUB_TOKEN", ""),
                        help="GitHub PAT with admin:org, repo scopes (or set GITHUB_TOKEN)")
    parser.add_argument("--mappings-dir", required=True,
                        help="Directory containing mapping CSV files")
    parser.add_argument("--inventory",
                        default="GitLab_UsersPermissions_Inventory.xlsx",
                        help="Path to inventory Excel (default: in mappings-dir)")
    parser.add_argument("--dry-run", action="store_true",
                        help="Simulate all actions without making changes")
    parser.add_argument("--skip-org-invite", action="store_true",
                        help="Skip org membership check/invite step")
    parser.add_argument("--skip-teams", action="store_true",
                        help="Skip team creation step")
    parser.add_argument("--skip-members", action="store_true",
                        help="Skip team member addition step")
    parser.add_argument("--skip-repos", action="store_true",
                        help="Skip repository permission step")
    parser.add_argument("--debug", action="store_true",
                        help="Enable debug logging")
    parser.add_argument("--version", action="version", version=f"%(prog)s {VERSION}")
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    if not args.github_token:
        print("ERROR: GitHub token required. Use --github-token or set GITHUB_TOKEN env var.", file=sys.stderr)
        sys.exit(1)

    mappings_dir = Path(args.mappings_dir).resolve()
    script_dir = Path(__file__).resolve().parent
    log_file = script_dir / DEFAULT_LOG_FILENAME

    setup_logging(log_file, args.debug)
    log.info("GitLab-to-GitHub Permission Migration v%s", VERSION)
    log.info("Target org: %s | Dry-run: %s", args.github_org, args.dry_run)

    # Load mapping files
    user_map = load_user_mapping(mappings_dir / "gitlab_to_github_user_mapping.csv")
    group_map = load_group_mapping(mappings_dir / "gitlab_to_github_group_mapping.csv")
    project_map = load_project_mapping(mappings_dir / "gitlab_to_github_project_mapping.csv")

    if not user_map:
        log.warning("No user mappings loaded — fill in 'github_username' column in the CSV")
    if not group_map:
        log.warning("No group mappings loaded — fill in 'github_team_slug' column in the CSV")

    # Load effective permissions from Excel
    inventory_path = mappings_dir / args.inventory
    if not inventory_path.exists():
        inventory_path = script_dir / args.inventory
    group_perms, project_perms = load_effective_permissions(inventory_path)

    # Initialize client and migrator
    client = GitHubClient(args.github_token, dry_run=args.dry_run)
    migrator = PermissionMigrator(
        client=client,
        org=args.github_org,
        user_map=user_map,
        group_map=group_map,
        project_map=project_map,
        group_perms=group_perms,
        project_perms=project_perms,
    )

    # Execute migration steps
    start_time = time.time()

    if not args.skip_org_invite:
        migrator.ensure_org_membership()

    if not args.skip_teams:
        migrator.create_teams()

    if not args.skip_members:
        migrator.add_team_members()

    if not args.skip_repos:
        migrator.set_repo_permissions()

    migrator.print_summary()

    elapsed = time.time() - start_time
    mode = "DRY-RUN" if args.dry_run else "LIVE"
    log.info("[%s] Migration completed in %.1f seconds", mode, elapsed)
    print(f"  [{mode}] Completed in {elapsed:.1f}s")


if __name__ == "__main__":
    main()

@dataclass
class UserMapping:
    gitlab_user_id: int
    gitlab_username: str
    name: str
    email: str
    github_username: str


@dataclass
class GroupMapping:
    gitlab_group_id: int
    gitlab_group_path: str
    depth: int
    parent_group_path: str
    github_org: str
    github_team_slug: str
    github_team_parent: str


@dataclass
class ProjectMapping:
    gitlab_project_id: int
    gitlab_project_path: str
    visibility: str
    github_org: str
    github_repo_name: str
    github_visibility: str


def load_user_mapping(path: Path) -> dict[str, UserMapping]:
    """Load user mapping CSV. Key: gitlab_username."""
    mappings: dict[str, UserMapping] = {}
    if not path.exists():
        log.warning("User mapping file not found: %s", path)
        return mappings
    with open(path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            gh_user = row.get("github_username", "").strip()
            if not gh_user:
                continue  # Skip unmapped users
            mappings[row["gitlab_username"]] = UserMapping(
                gitlab_user_id=int(row.get("gitlab_user_id", 0)),
                gitlab_username=row["gitlab_username"],
                name=row.get("name", ""),
                email=row.get("email", ""),
                github_username=gh_user,
            )
    log.info("Loaded %d user mappings (skipped unmapped)", len(mappings))
    return mappings


def load_group_mapping(path: Path) -> dict[str, GroupMapping]:
    """Load group mapping CSV. Key: gitlab_group_path."""
    mappings: dict[str, GroupMapping] = {}
    if not path.exists():
        log.warning("Group mapping file not found: %s", path)
        return mappings
    with open(path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            slug = row.get("github_team_slug", "").strip()
            if not slug:
                continue  # Skip unmapped groups
            mappings[row["gitlab_group_path"]] = GroupMapping(
                gitlab_group_id=int(row.get("gitlab_group_id", 0)),
                gitlab_group_path=row["gitlab_group_path"],
                depth=int(row.get("depth", 0)),
                parent_group_path=row.get("parent_group_path", ""),
                github_org=row.get("github_org", "").strip(),
                github_team_slug=slug,
                github_team_parent=row.get("github_team_parent", "").strip(),
            )
    log.info("Loaded %d group mappings (skipped unmapped)", len(mappings))
    return mappings


def load_project_mapping(path: Path) -> dict[str, ProjectMapping]:
    """Load project mapping CSV. Key: gitlab_project_path."""
    mappings: dict[str, ProjectMapping] = {}
    if not path.exists():
        log.warning("Project mapping file not found: %s", path)
        return mappings
    with open(path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            repo = row.get("github_repo_name", "").strip()
            if not repo:
                continue
            mappings[row["gitlab_project_path"]] = ProjectMapping(
                gitlab_project_id=int(row.get("gitlab_project_id", 0)),
                gitlab_project_path=row["gitlab_project_path"],
                visibility=row.get("visibility", "private"),
                github_org=row.get("github_org", "").strip(),
                github_repo_name=repo,
                github_visibility=row.get("github_visibility", "private"),
            )
    log.info("Loaded %d project mappings (skipped unmapped)", len(mappings))
    return mappings



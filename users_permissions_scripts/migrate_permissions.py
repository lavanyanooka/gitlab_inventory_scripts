def load_effective_permissions(excel_path: Path) -> tuple[list[dict], list[dict]]:
    """Load effective group and project permissions from the inventory Excel."""
    try:
        import openpyxl
    except ImportError:
        log.error("openpyxl is required: pip install openpyxl")
        sys.exit(1)

    if not excel_path.exists():
        log.error("Inventory Excel not found: %s", excel_path)
        sys.exit(1)

    wb = openpyxl.load_workbook(str(excel_path), read_only=True)

    def read_sheet(name: str) -> list[dict]:
        if name not in wb.sheetnames:
            log.warning("Sheet '%s' not found in workbook", name)
            return []
        ws = wb[name]
        rows = list(ws.iter_rows(values_only=True))
        if not rows:
            return []
        headers = [str(h) for h in rows[0]]
        return [dict(zip(headers, row)) for row in rows[1:]]

    group_perms = read_sheet("EffectiveGroupPermissions")
    project_perms = read_sheet("EffectiveProjectPermissions")
    wb.close()

    log.info("Loaded %d effective group perms, %d effective project perms from Excel",
             len(group_perms), len(project_perms))
    return group_perms, project_perms



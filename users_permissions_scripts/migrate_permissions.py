class PermissionMigrator:
    """Executes the GitHub permission migration."""

    def __init__(self, client: GitHubClient, org: str,
                 user_map: dict[str, UserMapping],
                 group_map: dict[str, GroupMapping],
                 project_map: dict[str, ProjectMapping],
                 group_perms: list[dict],
                 project_perms: list[dict]):
        self.client = client
        self.org = org
        self.user_map = user_map
        self.group_map = group_map
        self.project_map = project_map
        self.group_perms = group_perms
        self.project_perms = project_perms

        # Tracking
        self.teams_created: list[str] = []
        self.teams_updated: list[str] = []
        self.teams_skipped: list[str] = []
        self.org_members_existing: list[str] = []
        self.org_members_invited: list[str] = []
        self.org_members_failed: list[str] = []
        self.members_added: list[str] = []
        self.members_updated: list[str] = []
        self.members_skipped: list[str] = []
        self.members_failed: list[str] = []
        self.repo_perms_set: list[str] = []
        self.repo_perms_updated: list[str] = []
        self.repo_perms_skipped: list[str] = []
        self.repo_perms_failed: list[str] = []

    # ------------------------------------------------------------------
    # Org membership (pre-check)
    # ------------------------------------------------------------------

    def ensure_org_membership(self) -> None:
        """Ensure all mapped users are org members. Invite if not."""
        log.info("Checking org membership for %d mapped users in '%s'...",
                 len(self.user_map), self.org)

        for um in self.user_map.values():
            gh_user = um.github_username

            # Check current membership status
            resp = self.client.get(f"orgs/{self.org}/members/{gh_user}")
            if resp and resp.status_code == 204:
                # 204 = user is an active member
                log.debug("User '%s' is already an org member, skipping", gh_user)
                self.org_members_existing.append(gh_user)
                continue

            # Check if there's a pending invitation already
            resp_pending = self.client.get(
                f"orgs/{self.org}/invitations",
                params={"per_page": 100},
            )
            already_invited = False
            if resp_pending and resp_pending.status_code == 200:
                for inv in resp_pending.json():
                    if inv.get("login", "").lower() == gh_user.lower():
                        log.debug("User '%s' already has pending invitation, skipping", gh_user)
                        self.org_members_existing.append(f"{gh_user} (pending)")
                        already_invited = True
                        break
            if already_invited:
                continue

            # Add user to org via memberships API (invites if not already a member)
            invite_resp = self.client.put(
                f"orgs/{self.org}/memberships/{gh_user}",
                json={"role": "member"},
            )
            if invite_resp is None and self.client.dry_run:
                self.org_members_invited.append(gh_user)
            elif invite_resp and invite_resp.status_code in (200, 201):
                state = invite_resp.json().get("state", "unknown")
                if state == "active":
                    log.info("User '%s' added to org (already had account)", gh_user)
                else:
                    log.info("User '%s' invited to org (state: %s)", gh_user, state)
                self.org_members_invited.append(f"{gh_user} ({state})")
            else:
                status = invite_resp.status_code if invite_resp else "N/A"
                body = invite_resp.text[:200] if invite_resp else ""
                log.warning("Failed to invite '%s' to org: %s %s", gh_user, status, body)
                self.org_members_failed.append(gh_user)

        log.info("Org membership — existing: %d, invited: %d, failed: %d",
                 len(self.org_members_existing), len(self.org_members_invited),
                 len(self.org_members_failed))

    # ------------------------------------------------------------------
    # Teams
    # ------------------------------------------------------------------

    def create_teams(self) -> None:
        """Create GitHub teams from group mapping."""
        log.info("Creating GitHub teams in org '%s'...", self.org)

        # Sort by depth so parents are created before children
        sorted_groups = sorted(self.group_map.values(), key=lambda g: g.depth)

        for gm in sorted_groups:
            org = gm.github_org or self.org
            slug = gm.github_team_slug

            # Resolve desired parent team ID
            desired_parent_id: int | None = None
            if gm.github_team_parent:
                parent_resp = self.client.get(f"orgs/{org}/teams/{gm.github_team_parent}")
                if parent_resp and parent_resp.status_code == 200:
                    desired_parent_id = parent_resp.json()["id"]

            # Check if team already exists
            resp = self.client.get(f"orgs/{org}/teams/{slug}")
            if resp and resp.status_code == 200:
                existing = resp.json()
                existing_parent_id = existing.get("parent", {}).get("id") if existing.get("parent") else None

                # Check for mismatch: parent team changed
                if desired_parent_id != existing_parent_id:
                    log.info("Team '%s' exists but parent mismatch (current=%s, desired=%s), updating",
                             slug, existing_parent_id, desired_parent_id)
                    update_payload: dict[str, Any] = {
                        "name": slug,
                        "description": f"Migrated from GitLab group: {gm.gitlab_group_path}",
                        "privacy": "closed",
                    }
                    if desired_parent_id:
                        update_payload["parent_team_id"] = desired_parent_id
                    patch_resp = self.client.patch(f"orgs/{org}/teams/{slug}", json=update_payload)
                    if patch_resp is None and self.client.dry_run:
                        self.teams_updated.append(slug)
                    elif patch_resp and patch_resp.status_code == 200:
                        log.info("Updated team: %s", slug)
                        self.teams_updated.append(slug)
                    else:
                        status = patch_resp.status_code if patch_resp else "N/A"
                        log.error("Failed to update team '%s': %s", slug, status)
                else:
                    log.info("Team '%s' already exists with correct config, skipping", slug)
                    self.teams_skipped.append(slug)
                continue

            # Create team
            payload: dict[str, Any] = {
                "name": slug,
                "description": f"Migrated from GitLab group: {gm.gitlab_group_path}",
                "privacy": "closed",
            }
            if desired_parent_id:
                payload["parent_team_id"] = desired_parent_id

            resp = self.client.post(f"orgs/{org}/teams", json=payload)
            if resp is None and self.client.dry_run:
                self.teams_created.append(slug)
            elif resp and resp.status_code in (201, 200):
                log.info("Created team: %s", slug)
                self.teams_created.append(slug)
            else:
                status = resp.status_code if resp else "N/A"
                body = resp.text if resp else ""
                log.error("Failed to create team '%s': %s %s", slug, status, body)

        log.info("Teams created: %d, updated: %d, skipped (identical): %d",
                 len(self.teams_created), len(self.teams_updated), len(self.teams_skipped))

    # ------------------------------------------------------------------
    # Team memberships
    # ------------------------------------------------------------------

    def add_team_members(self) -> None:
        """Add users to GitHub teams based on effective group permissions."""
        log.info("Adding users to GitHub teams...")

        for perm in self.group_perms:
            gitlab_username = str(perm.get("Username", ""))
            group_path = str(perm.get("Group Path", ""))
            github_role_name = str(perm.get("GitHub Role", "Read"))

            # Resolve user mapping
            um = self.user_map.get(gitlab_username)
            if not um:
                continue  # User not mapped

            # Resolve group mapping
            gm = self.group_map.get(group_path)
            if not gm:
                continue  # Group not mapped

            org = gm.github_org or self.org
            team_slug = gm.github_team_slug
            team_role = ROLE_TO_TEAM_ROLE.get(github_role_name, "member")
            label = f"{um.github_username} → {team_slug} ({team_role})"

            # Check current membership
            check_resp = self.client.get(
                f"orgs/{org}/teams/{team_slug}/memberships/{um.github_username}"
            )
            if check_resp and check_resp.status_code == 200:
                current_data = check_resp.json()
                current_role = current_data.get("role", "")
                if current_role == team_role:
                    log.debug("Member '%s' already in team '%s' with role '%s', skipping",
                              um.github_username, team_slug, team_role)
                    self.members_skipped.append(label)
                    continue
                else:
                    log.info("Member '%s' in team '%s' has role '%s', updating to '%s'",
                             um.github_username, team_slug, current_role, team_role)

            # Add or update membership
            resp = self.client.put(
                f"orgs/{org}/teams/{team_slug}/memberships/{um.github_username}",
                json={"role": team_role},
            )
            if resp is None and self.client.dry_run:
                self.members_added.append(label)
            elif resp and resp.status_code in (200, 201):
                # Determine if this was an update or new addition
                if check_resp and check_resp.status_code == 200:
                    self.members_updated.append(label)
                else:
                    self.members_added.append(label)
            else:
                self.members_failed.append(label)
                log.warning("Failed to add %s to team %s", um.github_username, team_slug)

        log.info("Team members — added: %d, updated: %d, skipped (identical): %d, failed: %d",
                 len(self.members_added), len(self.members_updated),
                 len(self.members_skipped), len(self.members_failed))

    # ------------------------------------------------------------------
    # Repository permissions
    # ------------------------------------------------------------------

    def set_repo_permissions(self) -> None:
        """Set team permissions on repositories based on effective project permissions."""
        log.info("Setting repository permissions...")

        # Build: for each (project, group) → highest role needed
        # We assign team-level repo permissions (not individual user permissions)
        team_repo_perms: dict[tuple[str, str, str], str] = {}  # (org, team_slug, repo) → permission

        for perm in self.project_perms:
            gitlab_username = str(perm.get("Username", ""))
            project_path = str(perm.get("Project Path", ""))
            github_role_name = str(perm.get("GitHub Role", "Read"))
            inherited_from = str(perm.get("Inherited From", ""))

            # Resolve project mapping
            pm = self.project_map.get(project_path)
            if not pm:
                continue

            org = pm.github_org or self.org
            repo = pm.github_repo_name
            permission = ROLE_TO_REPO_PERMISSION.get(github_role_name, "pull")

            # If permission came from a group, assign at team level
            if inherited_from and inherited_from != "direct":
                # Find group mapping for the inherited source
                source_path = inherited_from.replace("shared:", "")
                gm = self.group_map.get(source_path)
                if gm:
                    key = (org, gm.github_team_slug, repo)
                    current = team_repo_perms.get(key)
                    if current is None or GITHUB_REPO_PERMISSIONS.index(permission) > GITHUB_REPO_PERMISSIONS.index(current):
                        team_repo_perms[key] = permission
                    continue

            # Direct permission → add user as collaborator (with idempotent check)
            um = self.user_map.get(gitlab_username)
            if um:
                label = f"{um.github_username} → {org}/{repo} ({permission})"

                # Check current collaborator permission
                check_resp = self.client.get(
                    f"repos/{org}/{repo}/collaborators/{um.github_username}/permission"
                )
                if check_resp and check_resp.status_code == 200:
                    current_perm = check_resp.json().get("permission", "")
                    # GitHub returns: admin, maintain, write(push), triage, read(pull)
                    # Normalize: GitHub uses "write" but API accepts "push", uses "read" but accepts "pull"
                    perm_normalize = {"write": "push", "read": "pull"}
                    current_normalized = perm_normalize.get(current_perm, current_perm)
                    if current_normalized == permission:
                        log.debug("Collaborator '%s' on '%s/%s' already has '%s', skipping",
                                  um.github_username, org, repo, permission)
                        self.repo_perms_skipped.append(label)
                        continue
                    else:
                        log.info("Collaborator '%s' on '%s/%s' has '%s', updating to '%s'",
                                 um.github_username, org, repo, current_normalized, permission)

                resp = self.client.put(
                    f"repos/{org}/{repo}/collaborators/{um.github_username}",
                    json={"permission": permission},
                )
                if resp is None and self.client.dry_run:
                    self.repo_perms_set.append(label)
                elif resp and resp.status_code in (200, 201, 204):
                    if check_resp and check_resp.status_code == 200:
                        self.repo_perms_updated.append(label)
                    else:
                        self.repo_perms_set.append(label)
                else:
                    self.repo_perms_failed.append(label)

        # Apply team-level repo permissions (with idempotent check)
        for (org, team_slug, repo), permission in team_repo_perms.items():
            label = f"team:{team_slug} → {org}/{repo} ({permission})"

            # Check current team permission on repo
            # Use special media type to get permissions in the response
            check_resp = self.client.get(
                f"orgs/{org}/teams/{team_slug}/repos/{org}/{repo}",
                headers={"Accept": "application/vnd.github.v3.repository+json"},
            )
            if check_resp and check_resp.status_code == 200:
                try:
                    resp_data = check_resp.json()
                    # Try role_name first (simpler), then fall back to permissions booleans
                    role_name = resp_data.get("role_name", "")
                    if role_name:
                        # role_name is: admin, maintain, write, triage, read
                        perm_normalize = {"write": "push", "read": "pull"}
                        current_level = perm_normalize.get(role_name, role_name)
                    else:
                        current_perms = resp_data.get("permissions", {})
                        current_level = "pull"
                        for lvl in GITHUB_REPO_PERMISSIONS:
                            if current_perms.get(lvl, False):
                                current_level = lvl
                    if current_level == permission:
                        log.debug("Team '%s' on '%s/%s' already has '%s', skipping",
                                  team_slug, org, repo, permission)
                        self.repo_perms_skipped.append(label)
                        continue
                    else:
                        log.info("Team '%s' on '%s/%s' has '%s', updating to '%s'",
                                 team_slug, org, repo, current_level, permission)
                except (ValueError, KeyError):
                    pass  # Can't parse response, proceed with PUT
            elif check_resp and check_resp.status_code == 204:
                # 204 means team has access but no body returned (old API behavior)
                # Can't determine current level — treat as needs-update to ensure correct perm
                log.debug("Team '%s' on '%s/%s' has access (204), verifying permission level",
                          team_slug, org, repo)

            resp = self.client.put(
                f"orgs/{org}/teams/{team_slug}/repos/{org}/{repo}",
                json={"permission": permission},
            )
            if resp is None and self.client.dry_run:
                self.repo_perms_set.append(label)
            elif resp and resp.status_code in (200, 201, 204):
                if check_resp and check_resp.status_code in (200, 204):
                    self.repo_perms_updated.append(label)
                else:
                    self.repo_perms_set.append(label)
            else:
                self.repo_perms_failed.append(label)

        log.info("Repo permissions — set: %d, updated: %d, skipped (identical): %d, failed: %d",
                 len(self.repo_perms_set), len(self.repo_perms_updated),
                 len(self.repo_perms_skipped), len(self.repo_perms_failed))

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------

    def print_summary(self) -> None:
        separator = "=" * 60
        print(f"\n{separator}")
        print("  GitHub Permission Migration Summary")
        print(separator)
        print(f"  Org members existing:  {len(self.org_members_existing):>6}")
        print(f"  Org members invited:   {len(self.org_members_invited):>6}")
        print(f"  Org members failed:    {len(self.org_members_failed):>6}")
        print(f"  Teams created:         {len(self.teams_created):>6}")
        print(f"  Teams updated:         {len(self.teams_updated):>6}")
        print(f"  Teams skipped:         {len(self.teams_skipped):>6}")
        print(f"  Members added:         {len(self.members_added):>6}")
        print(f"  Members updated:       {len(self.members_updated):>6}")
        print(f"  Members skipped:       {len(self.members_skipped):>6}")
        print(f"  Members failed:        {len(self.members_failed):>6}")
        print(f"  Repo perms set:        {len(self.repo_perms_set):>6}")
        print(f"  Repo perms updated:    {len(self.repo_perms_updated):>6}")
        print(f"  Repo perms skipped:    {len(self.repo_perms_skipped):>6}")
        print(f"  Repo perms failed:     {len(self.repo_perms_failed):>6}")
        print(separator)

        if self.org_members_failed:
            print("\n  Failed org invitations:")
            for item in self.org_members_failed[:20]:
                print(f"    - {item}")

        if self.teams_updated:
            print("\n  Updated teams (mismatch fixed):")
            for item in self.teams_updated[:20]:
                print(f"    - {item}")

        if self.members_updated:
            print("\n  Updated members (role changed):")
            for item in self.members_updated[:20]:
                print(f"    - {item}")

        if self.repo_perms_updated:
            print("\n  Updated repo permissions (mismatch fixed):")
            for item in self.repo_perms_updated[:20]:
                print(f"    - {item}")

        if self.members_failed:
            print("\n  Failed member additions:")
            for item in self.members_failed[:20]:
                print(f"    - {item}")

        if self.repo_perms_failed:
            print("\n  Failed repo permissions:")
            for item in self.repo_perms_failed[:20]:
                print(f"    - {item}")
        print()


